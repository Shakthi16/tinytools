const colors: Record<string, string> = {
  pink: 'bg-pink',
  lime: 'bg-lime',
  yellow: 'bg-yellow',
  mint: 'bg-mint',
  sky: 'bg-sky',
};

export function ToolIcon({ icon, color }: { icon: string; color: string }) {
  const Icon = icons[icon] ?? Type;
  return (
    <span className={`tool-icon ${colors[color] ?? 'bg-yellow'}`}>
      <Icon size={24} strokeWidth={1.8} />
    </span>
  );
}
